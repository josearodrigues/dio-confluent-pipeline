-- Inicializa o banco do laboratório. Operação destrutiva e explicitamente protegida.
\if :{?reset_ok}
  \echo 'Reset autorizado: removendo o schema payments.'
  DROP SCHEMA IF EXISTS payments CASCADE;
\else
  \echo 'ERRO: execute com CONFIRM_RESET=yes para recriar o schema payments.'
  \quit 3
\endif

\if :{?cdc_role}
\else
  \echo 'ERRO: informe a role CDC com -v cdc_role=<nome>.'
  \quit 3
\endif

CREATE SCHEMA payments;
SET search_path TO payments, public;

CREATE TABLE customers (
  customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  city TEXT NOT NULL
);

CREATE TABLE accounts (
  account_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INT NOT NULL REFERENCES customers(customer_id),
  account_type TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active'
);

CREATE TABLE cards (
  card_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id INT NOT NULL REFERENCES accounts(account_id),
  card_type TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active'
);

CREATE TABLE transactions (
  transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id INT NOT NULL REFERENCES cards(card_id),
  account_id INT NOT NULL REFERENCES accounts(account_id),
  merchant_id INT NOT NULL,
  amount NUMERIC(15,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'BRL',
  status TEXT NOT NULL DEFAULT 'approved',
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

