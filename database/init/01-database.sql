-- Inicializa o banco do laboratório com dataset determinístico.
-- Destrutivo: recria somente o schema payments.
-- Execute após habilitar logical replication e preparar a role cdc:
-- CONFIRM_RESET=yes ./scripts/run-sql.sh database/init/01-database.sql

\if :{?reset_ok}
  \echo 'Reset autorizado: removendo o schema payments.'
\else
  \echo 'ERRO: execute com CONFIRM_RESET=yes para recriar o schema payments.'
  \quit 3
\endif

\if :{?cdc_role}
\else
  \echo 'ERRO: informe a role PostgreSQL que será usada pelo conector.'
  \quit 3
\endif

BEGIN;

DROP SCHEMA IF EXISTS payments CASCADE;
CREATE SCHEMA payments;
SET search_path TO payments, public;

CREATE TABLE customers (
  customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  city TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE accounts (
  account_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INT NOT NULL REFERENCES customers(customer_id),
  account_type TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  opened_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE cards (
  card_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id INT NOT NULL REFERENCES accounts(account_id),
  card_type TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  expires_at DATE NOT NULL
);

-- merchants é dimensão auxiliar: faz parte do dataset do mentor,
-- mas não integra a publication nem o escopo CDC deste desafio.
CREATE TABLE merchants (
  merchant_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  city TEXT NOT NULL
);

CREATE TABLE transactions (
  transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id INT NOT NULL REFERENCES cards(card_id),
  account_id INT NOT NULL REFERENCES accounts(account_id),
  merchant_id INT NOT NULL REFERENCES merchants(merchant_id),
  amount NUMERIC(15,2) NOT NULL CHECK (amount > 0),
  currency CHAR(3) NOT NULL DEFAULT 'BRL',
  status TEXT NOT NULL DEFAULT 'approved',
  created_at TIMESTAMPTZ NOT NULL
);

-- Dataset fixo e reproduzível: 200 / 240 / 320 / 30 / 2.000.
INSERT INTO customers (customer_id, full_name, email, city, created_at)
SELECT g, 'Customer ' || g, 'customer' || g || '@example.test',
       (ARRAY['Rio de Janeiro','São Paulo','Brasília','Curitiba'])[((g-1)%4)+1],
       TIMESTAMPTZ '2025-01-01 00:00:00+00' + (g || ' hours')::interval
FROM generate_series(1, 200) AS g;

INSERT INTO accounts (account_id, customer_id, account_type, status, opened_at)
SELECT g, 1 + ((g-1)%200),
       CASE WHEN g%2=0 THEN 'checking' ELSE 'savings' END,
       'active',
       TIMESTAMPTZ '2025-01-02 00:00:00+00' + (g || ' hours')::interval
FROM generate_series(1, 240) AS g;

INSERT INTO cards (card_id, account_id, card_type, status, expires_at)
SELECT g, 1 + ((g-1)%240),
       CASE WHEN g%2=0 THEN 'credit' ELSE 'debit' END,
       'active',
       DATE '2028-01-01' + (g % 1000)
FROM generate_series(1, 320) AS g;

INSERT INTO merchants (merchant_id, name, category, city)
SELECT g, 'Merchant ' || g,
       (ARRAY['supermarket','restaurant','fuel','pharmacy','e-commerce','transport'])[((g-1)%6)+1],
       (ARRAY['Rio de Janeiro','São Paulo','Brasília','Curitiba'])[((g-1)%4)+1]
FROM generate_series(1, 30) AS g;

INSERT INTO transactions
  (transaction_id, card_id, account_id, merchant_id, amount, currency, status, created_at)
SELECT g,
       1 + ((g-1)%320),
       c.account_id,
       1 + ((g-1)%30),
       (10 + (g%990))::numeric(15,2),
       'BRL',
       'approved',
       TIMESTAMPTZ '2025-10-01 00:00:00+00' + (g * INTERVAL '37 minutes')
FROM generate_series(1, 2000) AS g
JOIN cards c ON c.card_id = 1 + ((g-1)%320);

-- Mantém os próximos IDs acima dos valores inseridos explicitamente.
SELECT setval(pg_get_serial_sequence('payments.customers','customer_id'), 200, true);
SELECT setval(pg_get_serial_sequence('payments.accounts','account_id'), 240, true);
SELECT setval(pg_get_serial_sequence('payments.cards','card_id'), 320, true);
SELECT setval(pg_get_serial_sequence('payments.merchants','merchant_id'), 30, true);
SELECT setval(pg_get_serial_sequence('payments.transactions','transaction_id'), 2000, true);

-- Permissões da role de conexão do conector; a role deve existir e ter
-- LOGIN + REPLICATION (verificados pelo wrapper antes de qualquer DROP).
GRANT CONNECT ON DATABASE :"DBNAME" TO :"cdc_role";
GRANT USAGE ON SCHEMA payments TO :"cdc_role";
GRANT SELECT ON ALL TABLES IN SCHEMA payments TO :"cdc_role";
ALTER DEFAULT PRIVILEGES IN SCHEMA payments
  GRANT SELECT ON TABLES TO :"cdc_role";

-- Debezium precisa do estado completo da linha em UPDATE/DELETE.
ALTER TABLE customers REPLICA IDENTITY FULL;
ALTER TABLE accounts REPLICA IDENTITY FULL;
ALTER TABLE cards REPLICA IDENTITY FULL;
ALTER TABLE transactions REPLICA IDENTITY FULL;

-- A publication contém somente as quatro tabelas declaradas no connector.json.
DROP PUBLICATION IF EXISTS payments_pub;
CREATE PUBLICATION payments_pub FOR TABLE
  payments.customers, payments.accounts, payments.cards, payments.transactions;

-- Asserções: qualquer divergência aborta e reverte a transação.
DO $$
BEGIN
  IF (SELECT count(*) FROM payments.customers) <> 200
     OR (SELECT count(*) FROM payments.accounts) <> 240
     OR (SELECT count(*) FROM payments.cards) <> 320
     OR (SELECT count(*) FROM payments.merchants) <> 30
     OR (SELECT count(*) FROM payments.transactions) <> 2000 THEN
    RAISE EXCEPTION 'Dataset divergente das contagens esperadas do mentor';
  END IF;

  IF (SELECT count(*) FROM pg_publication_tables
      WHERE pubname = 'payments_pub') <> 4 THEN
    RAISE EXCEPTION 'payments_pub deve conter exatamente quatro tabelas';
  END IF;
END
$$;

COMMIT;

-- Resultado visível da validação da carga.
SELECT 'customers' AS tabela, count(*) AS registros FROM payments.customers
UNION ALL SELECT 'accounts', count(*) FROM payments.accounts
UNION ALL SELECT 'cards', count(*) FROM payments.cards
UNION ALL SELECT 'merchants', count(*) FROM payments.merchants
UNION ALL SELECT 'transactions', count(*) FROM payments.transactions
ORDER BY tabela;

SELECT schemaname, tablename
FROM pg_publication_tables
WHERE pubname = 'payments_pub'
ORDER BY tablename;
